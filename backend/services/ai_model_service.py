def create_ai_model(model_data: Dict[str, Any], current_user_id: str = "admin") -> Dict[str, Any]:
    """
    Creates a new model in GSVAI_AI_MODELS with full validation and transactional safety.
    """
    ensure_ai_models_table()

    provider = (model_data.get("provider") or "").strip()
    model_name = (model_data.get("model_name") or "").strip()
    model_type = (model_data.get("model_type") or "LLM").strip().upper()
    priority = int(model_data.get("priority", 1))
    enabled = 1 if model_data.get("enabled", True) else 0
    is_primary = 1 if model_data.get("is_primary", False) else 0
    is_fallback = 1 if model_data.get("is_fallback", False) else 0
    temperature = float(model_data.get("temperature", 0.20))
    max_tokens = int(model_data.get("max_tokens", 4096))
    description = (model_data.get("description") or "").strip()

    # Validations
    if provider not in SUPPORTED_PROVIDERS:
        raise ValueError(f"Provider '{provider}' is not supported. Supported providers are: {', '.join(SUPPORTED_PROVIDERS)}")

    if not model_name:
        raise ValueError("Model name cannot be empty.")

    if model_type not in SUPPORTED_MODEL_TYPES:
        raise ValueError(f"Model type '{model_type}' is not supported. Supported types: {', '.join(SUPPORTED_MODEL_TYPES)}")

    if priority < 1:
        raise ValueError("Priority must be 1 or greater.")

    if is_primary and is_fallback:
        raise ValueError("A model cannot simultaneously be designated as both Primary and Fallback.")

    if is_primary and not enabled:
        raise ValueError("Cannot set a disabled model as primary.")

    if is_fallback and not enabled:
        raise ValueError("Cannot set a disabled model as fallback.")

    runtime_type = "API" if provider == "Groq" else "LOCAL"

    conn = get_connection()
    cursor = conn.cursor()
    try:
        # Check duplicate
        cursor.execute(
            "SELECT COUNT(*) FROM GSVAI_AI_MODELS WHERE UPPER(PROVIDER) = UPPER(:provider) AND UPPER(MODEL_NAME) = UPPER(:model_name)",
            {"provider": provider, "model_name": model_name},
        )
        if cursor.fetchone()[0] > 0:
            raise ValueError(f"Model '{model_name}' for provider '{provider}' is already configured in the registry.")

        # If primary requested, clear existing primary
        if is_primary:
            cursor.execute("UPDATE GSVAI_AI_MODELS SET IS_PRIMARY = 0 WHERE IS_PRIMARY = 1")

        # If fallback requested, clear existing fallback
        if is_fallback:
            cursor.execute("UPDATE GSVAI_AI_MODELS SET IS_FALLBACK = 0 WHERE IS_FALLBACK = 1")

        out_id = cursor.var(int)
        cursor.execute(
            """
            INSERT INTO GSVAI_AI_MODELS (
                PROVIDER, MODEL_NAME, MODEL_TYPE, RUNTIME_TYPE,
                ENABLED, PRIORITY, IS_PRIMARY, IS_FALLBACK,
                TEMPERATURE, MAX_TOKENS, DESCRIPTION,
                CREATED_AT, UPDATED_AT
            ) VALUES (
                :provider, :model_name, :model_type, :runtime_type,
                :enabled, :priority, :is_primary, :is_fallback,
                :temperature, :max_tokens, :description,
                SYSTIMESTAMP, SYSTIMESTAMP
            ) RETURNING MODEL_ID INTO :out_id
            """,
            {
                "provider": provider,
                "model_name": model_name,
                "model_type": model_type,
                "runtime_type": runtime_type,
                "enabled": enabled,
                "priority": priority,
                "is_primary": is_primary,
                "is_fallback": is_fallback,
                "temperature": temperature,
                "max_tokens": max_tokens,
                "description": description,
                "out_id": out_id,
            },
        )
        new_model_id = out_id.getvalue()[0]
        conn.commit()

        log_audit_event(
            action="MODEL_CREATED",
            resource_type="AI_MODEL",
            resource_id=str(new_model_id),
            user_id=current_user_id,
            details={
                "provider": provider,
                "model_name": model_name,
                "model_type": model_type,
                "priority": priority,
                "is_primary": bool(is_primary),
                "is_fallback": bool(is_fallback),
            },
            status="SUCCESS",
        )

        return get_ai_model_by_id(new_model_id)
    except Exception:
        conn.rollback()
        raise
    finally:
        cursor.close()
        conn.close()


def update_ai_model(model_id: int, updates: Dict[str, Any], current_user_id: str = "admin") -> Dict[str, Any]:
    """
    Updates configuration parameters for an existing model.
    Enforces primary/fallback exclusivity and safe updates.
    """
    existing = get_ai_model_by_id(model_id)
    if not existing:
        raise ValueError(f"AI Model with ID {model_id} not found.")

    conn = get_connection()
    cursor = conn.cursor()
    try:
        model_name = updates.get("model_name", existing["model_name"]).strip()
        if not model_name:
            raise ValueError("Model name cannot be empty.")

        priority = int(updates.get("priority", existing["priority"]))
        if priority < 1:
            raise ValueError("Priority must be 1 or greater.")

        temperature = float(updates.get("temperature", existing["temperature"]))
        max_tokens = int(updates.get("max_tokens", existing["max_tokens"]))
        description = updates.get("description", existing["description"])

        enabled = existing["enabled"]
        if "enabled" in updates:
            enabled = bool(updates["enabled"])

        is_primary = existing["is_primary"]
        if "is_primary" in updates:
            is_primary = bool(updates["is_primary"])

        is_fallback = existing["is_fallback"]
        if "is_fallback" in updates:
            is_fallback = bool(updates["is_fallback"])

        # Constraints
        if is_primary and is_fallback:
            raise ValueError("A model cannot simultaneously be designated as both Primary and Fallback.")

        if is_primary and not enabled:
            raise ValueError("Cannot set a disabled model as primary.")

        if is_fallback and not enabled:
            raise ValueError("Cannot set a disabled model as fallback.")

        # Disabling active primary check
        if existing["is_primary"] and not enabled:
            raise ValueError("Cannot disable the current primary model without selecting an active replacement.")

        # Atomic primary clearing
        if is_primary and not existing["is_primary"]:
            cursor.execute("UPDATE GSVAI_AI_MODELS SET IS_PRIMARY = 0 WHERE IS_PRIMARY = 1")

        # Atomic fallback clearing
        if is_fallback and not existing["is_fallback"]:
            cursor.execute("UPDATE GSVAI_AI_MODELS SET IS_FALLBACK = 0 WHERE IS_FALLBACK = 1")

        cursor.execute(
            """
            UPDATE GSVAI_AI_MODELS
            SET
                MODEL_NAME   = :model_name,
                PRIORITY     = :priority,
                ENABLED      = :enabled,
                IS_PRIMARY   = :is_primary,
                IS_FALLBACK  = :is_fallback,
                TEMPERATURE  = :temperature,
                MAX_TOKENS   = :max_tokens,
                DESCRIPTION  = :description,
                UPDATED_AT   = SYSTIMESTAMP
            WHERE MODEL_ID   = :model_id
            """,
            {
                "model_name": model_name,
                "priority": priority,
                "enabled": 1 if enabled else 0,
                "is_primary": 1 if is_primary else 0,
                "is_fallback": 1 if is_fallback else 0,
                "temperature": temperature,
                "max_tokens": max_tokens,
                "description": description,
                "model_id": model_id,
            },
        )
        conn.commit()

        log_audit_event(
            action="MODEL_UPDATED",
            resource_type="AI_MODEL",
            resource_id=str(model_id),
            user_id=current_user_id,
            details={
                "provider": existing["provider"],
                "model_name": model_name,
                "is_primary": is_primary,
                "is_fallback": is_fallback,
                "enabled": enabled,
            },
            status="SUCCESS",
        )

        return get_ai_model_by_id(model_id)
    except Exception:
        conn.rollback()
        raise
    finally:
        cursor.close()
        conn.close()


