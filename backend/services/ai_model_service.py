def _check_ollama_online(timeout: float = 1.0) -> bool:
    """Probes local Ollama instance for live availability."""
    ollama_endpoint = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")
    try:
        resp = requests.get(f"{ollama_endpoint.rstrip('/')}/api/tags", timeout=timeout)
        return resp.status_code == 200
    except Exception:
        return False


def get_ai_models() -> List[Dict[str, Any]]:
    """
    Retrieves all configured AI models from GSVAI_AI_MODELS,
    ordered by primary, priority, and model name.
    Enriches with live health status without exposing any secrets.
    """
    ensure_ai_models_table()
    conn = get_connection()
    cursor = conn.cursor()
    try:
        cursor.execute(
            """
            SELECT
                MODEL_ID,
                PROVIDER,
                MODEL_NAME,
                MODEL_TYPE,
                RUNTIME_TYPE,
                ENABLED,
                PRIORITY,
                IS_PRIMARY,
                IS_FALLBACK,
                TEMPERATURE,
                MAX_TOKENS,
                DESCRIPTION,
                CREATED_AT,
                UPDATED_AT
            FROM GSVAI_AI_MODELS
            ORDER BY IS_PRIMARY DESC, PRIORITY ASC, MODEL_NAME ASC
            """
        )
        rows = cursor.fetchall()

        groq_key_configured = bool(os.getenv("GROQ_API_KEY"))
        ollama_online = _check_ollama_online()

        models = []
        for r in rows:
            provider = r[1]
            enabled = bool(r[5])
            is_primary = bool(r[7])
            is_fallback = bool(r[8])

            # Evaluate meaningful health status
            if not enabled:
                status_label = "Disabled"
            elif provider == "Groq":
                status_label = "Active" if (is_primary and groq_key_configured) else ("Configured" if groq_key_configured else "Unconfigured")
            elif provider == "Ollama":
                status_label = "Available" if ollama_online else "Unavailable"
            else:
                status_label = "Unknown"

            models.append({
                "model_id": r[0],
                "provider": provider,
                "model_name": r[2],
                "model_type": r[3],
                "runtime_type": r[4],
                "enabled": enabled,
                "priority": r[6],
                "is_primary": is_primary,
                "is_fallback": is_fallback,
                "temperature": float(r[9]) if r[9] is not None else 0.2,
                "max_tokens": r[10] or 4096,
                "description": r[11] or "",
                "status": status_label,
                "created_at": r[12].isoformat() if r[12] else None,
                "updated_at": r[13].isoformat() if r[13] else None,
            })
        return models
    finally:
        cursor.close()
        conn.close()


