def test_ai_model(model_id: int, current_user_id: str = "admin") -> Dict[str, Any]:
    """
    Executes a real connectivity and latency health test against the model.
    Never returns secrets, tokens, or system prompts.
    """
    existing = get_ai_model_by_id(model_id)
    if not existing:
        raise ValueError(f"AI Model with ID {model_id} not found.")

    provider = existing["provider"]
    model_name = existing["model_name"]
    start_time = time.time()

    if provider == "Groq":
        groq_api_key = os.getenv("GROQ_API_KEY")
        if not groq_api_key:
            return {
                "success": False,
                "provider": "Groq",
                "model": model_name,
                "latency_ms": 0,
                "error": "GROQ_API_KEY is not configured on the server.",
            }
        try:
            from groq import Groq
            client = Groq(api_key=groq_api_key)
            completion = client.chat.completions.create(
                model=model_name,
                messages=[{"role": "user", "content": "Respond with the single word: OK"}],
                max_completion_tokens=5,
                temperature=0.1,
            )
            latency_ms = int((time.time() - start_time) * 1000)
            log_audit_event(
                action="MODEL_TESTED",
                resource_type="AI_MODEL",
                resource_id=str(model_id),
                user_id=current_user_id,
                details={"provider": provider, "model": model_name, "success": True, "latency_ms": latency_ms},
                status="SUCCESS",
            )
            return {
                "success": True,
                "provider": "Groq",
                "model": model_name,
                "latency_ms": latency_ms,
                "message": f"Groq inference verified successfully ({latency_ms}ms).",
            }
        except Exception as e:
            latency_ms = int((time.time() - start_time) * 1000)
            err_msg = str(e)
            # Sanitize any key leakage in error messages
            if groq_api_key and groq_api_key in err_msg:
                err_msg = err_msg.replace(groq_api_key, "[REDACTED]")
            log_audit_event(
                action="MODEL_TESTED",
                resource_type="AI_MODEL",
                resource_id=str(model_id),
                user_id=current_user_id,
                details={"provider": provider, "model": model_name, "success": False, "latency_ms": latency_ms, "error": err_msg},
                status="FAILED",
            )
            return {
                "success": False,
                "provider": "Groq",
                "model": model_name,
                "latency_ms": latency_ms,
                "error": err_msg,
            }

    elif provider == "Ollama":
        ollama_endpoint = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")
        try:
            resp = requests.post(
                f"{ollama_endpoint.rstrip('/')}/api/generate",
                json={
                    "model": model_name,
                    "prompt": "Respond with OK",
                    "stream": False,
                    "options": {"num_predict": 5, "temperature": 0.1},
                },
                timeout=10,
            )
            latency_ms = int((time.time() - start_time) * 1000)
            if resp.status_code == 200:
                log_audit_event(
                    action="MODEL_TESTED",
                    resource_type="AI_MODEL",
                    resource_id=str(model_id),
                    user_id=current_user_id,
                    details={"provider": provider, "model": model_name, "success": True, "latency_ms": latency_ms},
                    status="SUCCESS",
                )
                return {
                    "success": True,
                    "provider": "Ollama",
                    "model": model_name,
                    "latency_ms": latency_ms,
                    "message": f"Local Ollama inference verified successfully ({latency_ms}ms).",
                }
            else:
                err_msg = f"Ollama HTTP {resp.status_code}: {resp.text}"
                log_audit_event(
                    action="MODEL_TESTED",
                    resource_type="AI_MODEL",
                    resource_id=str(model_id),
                    user_id=current_user_id,
                    details={"provider": provider, "model": model_name, "success": False, "latency_ms": latency_ms, "error": err_msg},
                    status="FAILED",
                )
                return {
                    "success": False,
                    "provider": "Ollama",
                    "model": model_name,
                    "latency_ms": latency_ms,
                    "error": err_msg,
                }
        except Exception as e:
            latency_ms = int((time.time() - start_time) * 1000)
            err_msg = str(e)
            log_audit_event(
                action="MODEL_TESTED",
                resource_type="AI_MODEL",
                resource_id=str(model_id),
                user_id=current_user_id,
                details={"provider": provider, "model": model_name, "success": False, "latency_ms": latency_ms, "error": err_msg},
                status="FAILED",
            )
            return {
                "success": False,
                "provider": "Ollama",
                "model": model_name,
                "latency_ms": latency_ms,
                "error": f"Failed to connect to local Ollama at {ollama_endpoint}: {err_msg}",
            }
    else:
        return {
            "success": False,
            "provider": provider,
            "model": model_name,
            "latency_ms": 0,
            "error": f"Testing not supported for provider '{provider}'.",
        }
